def zy(text, mantra):
    out = []
    for ch, py in zip(text, pinyin(text, style=Style.BOPOMOFO, errors=lambda x: [[''] for _ in x])):
        out.append((M.get(ch) if mantra else None) or (py[0] if han(ch) else '') or '_')
    return ' '.join(out)
def build(lst):
    res = []
    for t, ps in lst:
        paras, zs = [], []
        for p in ps:
            m = p.startswith(MT); p = p[len(MT):] if m else p
            # 括號內的（三稱）不套真言音
            z = zy(p, m).split(' ')
            if m and '（' in p:
                i = p.index('（'); z[i:] = zy(p[i:], False).split(' ')
            paras.append(p); zs.append(' '.join(z))
        res.append({'title': t, 'paras': paras, 'zt': zy(t, False), 'zp': zs, 'lit': True})
    return res

